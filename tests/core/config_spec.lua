describe("Config", function()
  local ns = Taxi.load()
  it("names", function()
    assert.are.equal("Taxi", ns.Config.NAME)
    assert.are.equal("TaxiFvr", ns.Config.PREFIX)
    assert.is_true(#ns.Config.PREFIX <= 16)
    assert.are.equal("TaxiForever", ns.Config.CHANNEL)
  end)
  it("spec values", function()
    assert.are.same({5000, 10000}, ns.Config.TIP_PRESETS)
    assert.are.equal(120, ns.Config.DEATH_WINDOW)
    assert.are.equal(0.2, ns.Config.RATING.W_RELAYED)
    assert.are.equal(500, ns.Config.RATING.CAP_PER_KIND)
  end)
  it("callbacks", function()
    local cb, got = ns.Callbacks.new(), nil
    local tok = cb:on("X", function(v) got = v end)
    cb:emit("X", 7); assert.are.equal(7, got)
    cb:off(tok); cb:emit("X", 9); assert.are.equal(7, got)
  end)
end)
