describe("Util", function()
  local U = Taxi.load().Util
  it("distance", function() assert.are.equal(5, U.distance(0,0,3,4)) end)
  it("day", function() assert.are.equal(1, U.day(86400 + 5)) end)
  it("trim", function() assert.are.equal("Ana Smith", U.trim("  Ana Smith ")); assert.is_nil(U.trim(nil)) end)

  it("distance is symmetric and zero for the same point", function()
    assert.are.equal(0, U.distance(7, -2, 7, -2))
    assert.are.equal(U.distance(1, 2, 4, 6), U.distance(4, 6, 1, 2))
    assert.are.equal(5, U.distance(-1, -1, 2, 3))
  end)
  it("day rolls over exactly at midnight UTC", function()
    assert.are.equal(0, U.day(0))
    assert.are.equal(0, U.day(86399))
    assert.are.equal(1, U.day(86400))
  end)
  it("trim keeps inner spaces, handles tabs and newlines, and returns '' for blanks", function()
    assert.are.equal("Ana  Smith", U.trim("\t Ana  Smith\n"))
    assert.are.equal("", U.trim("   "))
    assert.are.equal("Ana", U.trim("Ana"))
  end)
  it("trim returns nil for anything that is not a string", function()
    assert.is_nil(U.trim(42))
    assert.is_nil(U.trim({}))
  end)
  it("copy is shallow: new table, shared nested values", function()
    local inner = { 1 }
    local src = { a = 1, nested = inner }
    local dup = U.copy(src)
    assert.are_not.equal(src, dup)
    assert.are.equal(1, dup.a)
    assert.are.equal(inner, dup.nested)
    dup.a = 2
    assert.are.equal(1, src.a)
  end)
end)
