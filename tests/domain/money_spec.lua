describe("Money", function()
  local M = Taxi.load().Money

  it("parts", function()
    assert.are.equal(15000, M.fromParts(1, 50, 0))
    assert.is_nil(M.fromParts(0, 0, 0)); assert.is_nil(M.fromParts(-1, 0, 0)); assert.is_nil(M.fromParts(1.5, 0, 0))
  end)

  it("format", function()
    assert.are.equal("1g 50s", M.format(15000)); assert.are.equal("50s", M.format(5000)); assert.are.equal("25s 50c", M.format(2550))
  end)

  it("tip validation", function()
    assert.is_true(M.validateTip(5000, 9000))
    assert.are.same({nil, "too_much"}, {M.validateTip(10000, 9000)})
    assert.are.same({nil, "zero"}, {M.validateTip(0, 9000)})
  end)

  describe("fromParts", function()
    it("combines gold, silver and copper", function()
      assert.are.equal(10000, M.fromParts(1, 0, 0))
      assert.are.equal(5000, M.fromParts(0, 50, 0))
      assert.are.equal(7, M.fromParts(0, 0, 7))
      assert.are.equal(123456, M.fromParts(12, 34, 56))
    end)

    it("treats omitted parts as zero", function()
      assert.are.equal(20000, M.fromParts(2))
      assert.are.equal(5000, M.fromParts(nil, 50))
    end)

    it("rejects a negative or fractional part in any position", function()
      assert.is_nil(M.fromParts(0, -1, 0))
      assert.is_nil(M.fromParts(0, 0, -1))
      assert.is_nil(M.fromParts(5, -1, 0))
      assert.is_nil(M.fromParts(0, 1.5, 0))
      assert.is_nil(M.fromParts(0, 0, 0.5))
    end)

    it("rejects parts that are not numbers or not finite", function()
      assert.is_nil(M.fromParts("1", 0, 0))
      assert.is_nil(M.fromParts({}, 0, 0))
      assert.is_nil(M.fromParts(0 / 0, 0, 0))
      assert.is_nil(M.fromParts(math.huge, 0, 0))
      assert.is_nil(M.fromParts(1e308, 0, 0))
    end)
  end)

  describe("format", function()
    it("shows only the non-zero units, largest first", function()
      assert.are.equal("1g", M.format(10000))
      assert.are.equal("1g 1c", M.format(10001))
      assert.are.equal("1g 50s 25c", M.format(15025))
      assert.are.equal("5s", M.format(500))
      assert.are.equal("7c", M.format(7))
      assert.are.equal("100g", M.format(1000000))
    end)

    it("shows zero as 0c", function()
      assert.are.equal("0c", M.format(0))
    end)

    it("falls back to 0c rather than erroring on junk", function()
      assert.are.equal("0c", M.format(nil))
      assert.are.equal("0c", M.format("5000"))
      assert.are.equal("0c", M.format(-100))
      assert.are.equal("0c", M.format(0 / 0))
      assert.are.equal("0c", M.format(math.huge))
    end)

    it("round-trips with fromParts", function()
      assert.are.equal("12g 34s 56c", M.format(M.fromParts(12, 34, 56)))
    end)
  end)

  describe("validateTip", function()
    it("allows a tip up to everything the player has", function()
      assert.is_true(M.validateTip(9000, 9000))
      assert.is_true(M.validateTip(1, 9000))
    end)

    it("refuses a tip over the player's money", function()
      assert.are.same({nil, "too_much"}, {M.validateTip(9001, 9000)})
      assert.are.same({nil, "too_much"}, {M.validateTip(math.huge, 9000)})
    end)

    it("treats a missing or invalid player balance as no money", function()
      assert.are.same({nil, "too_much"}, {M.validateTip(1, nil)})
      assert.are.same({nil, "too_much"}, {M.validateTip(1, "9000")})
    end)

    it("calls anything that is not a positive whole amount zero", function()
      assert.are.same({nil, "zero"}, {M.validateTip(nil, 9000)})
      assert.are.same({nil, "zero"}, {M.validateTip(-5, 9000)})
      assert.are.same({nil, "zero"}, {M.validateTip(0.5, 9000)})
      assert.are.same({nil, "zero"}, {M.validateTip("5000", 9000)})
      assert.are.same({nil, "zero"}, {M.validateTip(0 / 0, 9000)})
    end)

    it("checks zero before money, so a broke player entering nothing gets zero", function()
      assert.are.same({nil, "zero"}, {M.validateTip(0, 0)})
    end)
  end)
end)
